async function readyImages(target){
  await target.locator('img').evaluateAll(imgs=>imgs.filter(img=>img.getClientRects().length>0).forEach(img=>img.loading='eager'));
  await target.waitForFunction(()=>[...document.images].filter(img=>img.getClientRects().length>0).every(img=>img.complete&&img.naturalWidth>0));
  await target.evaluate(async()=>{
    await Promise.all([...document.images].filter(img=>img.getClientRects().length>0).map(img=>img.decode()));
    for(let y=0;y<document.body.scrollHeight;y+=700){scrollTo({top:y,behavior:'instant'});await new Promise(resolve=>setTimeout(resolve,80))}
    scrollTo({top:0,behavior:'instant'});
    await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));
  });
}
